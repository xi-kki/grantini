// ── Main Edge handler ─────────────────────────────────────────────────
export default async function handler(req) {
  // CORS preflight
  if (req.method === 'OPTIONS') {
    return new Response(null, {
      headers: {
        'Access-Control-Allow-Origin': '*',
        'Access-Control-Allow-Methods': 'POST, OPTIONS',
        'Access-Control-Allow-Headers': 'Content-Type',
      },
    });
  }

  if (req.method !== 'POST') {
    return new Response('Method not allowed', { status: 405 });
  }

  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) {
    return new Response(
      JSON.stringify({ error: 'Server misconfiguration: GROQ_API_KEY missing.' }),
      { status: 500, headers: { 'Content-Type': 'application/json' } }
    );
  }

  let body;
  try {
    body = await req.json();
  } catch {
    return new Response('Invalid JSON body', { status: 400 });
  }

  const { url, description } = body;
  if (!url && !description) {
    return new Response('Provide at least one of: url, description', { status: 400 });
  }

  // Build context
  let context = '';
  if (url)         context += await fetchUrl(url);
  if (description) context += (context ? '\n\nAdditional context:\n' : '') + description;

  // Call Groq (streamed)
  const groqResp = await fetch(GROQ_URL, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model: 'llama-3.3-70b-versatile',
      messages: [
        {
          role: 'system',
          content:
            'You are Grantini, a world-class grant researcher. You are precise, specific, and only name real grant programs. You write in clear, professional, actionable language.',
        },
        { role: 'user', content: buildPrompt(context) },
      ],
      stream: true,
      max_tokens: 6000,
      temperature: 0.35,
    }),
  });

  if (!groqResp.ok) {
    const err = await groqResp.text();
    return new Response(JSON.stringify({ error: `Groq error: ${err}` }), {
      status: groqResp.status,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  // Forward Groq's SSE stream directly to the client
  return new Response(groqResp.body, {
    headers: {
      'Content-Type': 'text/event-stream',
      'Cache-Control': 'no-cache, no-transform',
      'X-Accel-Buffering': 'no',
      'Access-Control-Allow-Origin': '*',
    },
  });
}
