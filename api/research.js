const GROQ_URL = 'https://api.groq.com/openai/v1/chat/completions';

// ── Strip HTML to plain text ──────────────────────────────────────────
function stripHtml(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&nbsp;/g, ' ').replace(/&#\d+;/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 6000);
}

// ── Fetch project URL content ─────────────────────────────────────────
async function fetchUrl(url) {
  try {
    const resp = await fetch(url, {
      headers: { 'User-Agent': 'Grantini/1.0 (+https://github.com/xi-kki/grantini)' },
      signal: AbortSignal.timeout(7000),
    });
    const html = await resp.text();
    return `Website content (${url}):\n${stripHtml(html)}`;
  } catch {
    return `Project URL: ${url}\n(Could not fetch page — used URL as context only.)`;
  }
}

